/**
 * Статический список: textometr.ru (простые слова для детей) + доп. слова для рисования.
 * Run: node scripts/build-children-words.mjs
 */
import fs from "fs";
import path from "path";
import { fileURLToPath } from "url";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const outPath = path.join(__dirname, "..", "words-children.json");

const fromTextometrNouns = `
мама день друг дом год папа школа город бабушка ребенок человек девочка мальчик
стол окно машина вечер утро брат книга собака сестра дедушка семья рука вода
комната ночь улица лес двор дерево море чай хлеб стул сад цветок лето рыба игра
магазин кот кошка подарок праздник автобус телевизор молоко парк мяч карандаш
яблоко сок футбол глаз голова дверь нога отец земля свет дорога телефон гость подруга
`.trim().split(/\s+/);

const extraDrawable = `
снег дождь радуга солнце луна звезда небо облако зима осень весна медведь волк лиса
заяц белка лошадь корова свинья овца коза мышь кролик хомяк попугай голубь утка гусь
курица петух кит дельфин черепаха лягушка змея крокодил динозавр слон жираф зебра
обезьяна панда бегемот бабочка пчела муравей жук щенок котенок робот ракета принцесса
рыцарь меч корона замок ключ кровать диван шкаф лампа зеркало ванна кухня забор гараж
поезд самолет лодка велосипед самокат мост река озеро пляж гора песок трава лист гриб
арбуз дыня банан апельсин лимон клубника морковь огурец помидор капуста картофель суп
торт пирог пицца сыр яйцо конфета шоколад мороженое мишка кукла кубик гитара шапка
платье носки ботинок зонт очки свеча шарик фонарь качели горка песочница санки лыжи
шар мыло нос рот ухо палец хвост гнездо фонтан скамейка кораблик трамвай мотоцикл
светофор лифт подушка ведро лопата лейка ромашка тюльпан роза
`.trim().split(/\s+/);

const SKIP = new Set([
  "день", "год", "ребенок", "время", "раз", "место", "работа", "вопрос", "дело", "вид",
  "страна", "язык", "спасибо", "привет", "неделя", "минуца", "минута", "ученик", "учитель",
  "врач", "театр", "музей", "билет", "рубль", "фотография", "фрукт", "рождение", "цвет",
  "урок", "ребята", "слово", "сын", "дядя", "тетя", "класс"
]);

const reWord = /^[а-яё]+$/;
const set = new Set();

for (const raw of [...fromTextometrNouns, ...extraDrawable]) {
  const w = raw.toLowerCase().replace(/ё/g, "е");
  if (w.length < 2 || w.length > 12) continue;
  if (!reWord.test(w)) continue;
  if (SKIP.has(w)) continue;
  set.add(w);
}

const words = [...set].sort((a, b) => a.localeCompare(b, "ru"));
fs.writeFileSync(outPath, JSON.stringify(words));
console.log("Wrote", words.length, "words to", outPath);
